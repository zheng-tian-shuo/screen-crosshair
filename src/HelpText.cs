        /// <summary>程序名。窗口标题、托盘提示、配置文件表头都从这里取，改名只改这一处。</summary>
        public const string AppName = "得吃准星";

        public const string Readme = @"## 这是什么
纯屏幕覆盖层准星，给《三角洲行动》炸撤离点这类需要固定屏幕参考点的玩法用。
只在屏幕最上层画图：不读游戏内存、不注入进程、不改游戏文件、不装键盘钩子。

## 五步上手
1. 运行程序，这个窗口就是设置面板，右边一直有实时预览。
2. 「准星」页上半段：选形状，调颜色、大小、线宽、透明度、发光。
3. 「准星」页下半段：取消「屏幕居中」就能自由摆放，点「屏幕取点」直接在屏幕上点一下定位。
4. 「倒计时」页：设置自由倒计时的时长、屏幕上的显示样式，还能常显北京时间；三个倒计时的热键在「热键」页。
5. 关掉这个窗口 = 收进托盘，准星照常显示。默认 F8 显示/隐藏全部，Ctrl+F8 切换下一套预设，
  都能在「热键」页改。

## 炸撤离点的用法
- 先固定一个站位打一发，看落点在屏幕的哪个位置。
- 回「准星」页点「屏幕取点」，鼠标移到刚才那个落点上左键点一下，准星就钉死在那里。
- 如果要切换 FOV，先在原 FOV 下用「FOV 坐标换算」记录当前点，再填目标 FOV 并计算应用；程序会按屏幕中心、基准分辨率和 FOV 缩放。
- FOV 校准后点击「新建原本准星」，会另建一个准星并放回基准 FOV 记录的原始位置。
- 要标一串距离，形状选「分划板」：一根竖尺加若干横刻度，刻度旁边能显示米数
  （起始距离和每格递增都能自己填），之后按格数抬枪就行。
- 一张图一套：在「预设」页给每个地图/撤离点存一套准星组合，进图前 Ctrl+F8 切。
- 要标水平基准（楼层高度、地平线），用「水平线」形状拉长一点。

## 屏幕时钟
- 「倒计时」页最下面勾上「在屏幕上常显北京时间」，时间就挂在倒计时面板最上面一行，
  时间现在是独立覆盖层，可在「倒计时」页单独拖动定位；不想要秒可以只显示时和分。
- 无边框全屏时任务栏的钟被挡住，看时间靠这一行。
- 按 UTC+8 直接算，不看系统时区、不联网，读的是本机时钟。
- 这块面板不受 F8 和自动显隐控制，不想看就回「倒计时」页取消勾选。

## 形状怎么选
- 圆点 / 点 + 外圈：最不挡视野，杂色背景上「点 + 外圈」最好找。
- 十字 / 圆环十字：常规瞄准，圆环十字中心有缺口，落点看得清。
- T 形：中心下方完全留空，专门用来看落地爆点。
- 水平线：标水平面、楼层高度。
- 分划板：竖刻度尺，一次标一串距离。

## 热键与托盘
- 五条热键全在「热键」页：显示/隐藏全部、切换预设、撤离点、火箭、自由倒计时。
- 每条右边都有一个「已启用 / 已停用」按钮，按一下立刻生效。停用只是不再注册这个组合，
  组合键本身留着，重新启用就回来——和游戏里的按键撞了就把它停用，不用清空。
- 显示/隐藏全部：默认 F8。切换预设：默认 Ctrl+F8，按一下轮到下一套。
- 倒计时：默认 Alt+F1 为撤离点 5:00，Alt+F2 为火箭 4:30，Alt+F3 为自由倒计时；
  按一下开始或重新开始对应计时，倒计时结束后面板自动隐藏。自由倒计时的时长在「倒计时」页填。
- 改完组合键要按「应用热键」；提示「被占用」说明被别的程序抢了，换一个组合或先停用。
- 托盘图标：双击打开设置，右键菜单可以显示/隐藏、切预设、退出。

## 多显示器
- 每个准星都能单独指定显示在哪块屏（「准星」页的目标屏幕）。
- 选「跟随鼠标所在屏」时，准星跟着你正在操作的那块屏走。
- 坐标相对所选屏幕的左上角；FOV 换算会记录基准分辨率，宽高比不变时可直接换算。

## 必读注意
- 游戏必须用窗口化或无边框窗口。独占全屏下 Windows 不允许任何覆盖层画在游戏上面，
  所有同类工具都一样，不是本程序的问题。
- 准星默认鼠标穿透，不会挡住点击；只有在「拖动定位」状态下才能被鼠标抓住。
- 本程序不与游戏进程发生任何交互，但第三方覆盖层仍有被反作弊误判的可能，
  是否使用请自行判断。

## 便携与配置
- 整个程序就是一个 exe，不用安装、不写注册表。
- 配置存在 exe 同目录的 settings.ini，纯文本，可以直接用记事本改。
- 如果放在没有写权限的目录（比如 Program Files），配置会自动退到
  %AppData%\ScreenCrosshair\settings.ini。
- 分享给朋友：把 exe 拷过去就行；想连设置一起带走就把 settings.ini 也拷过去。
- 「预设」页可以把配置导出成单独的 .ini 文件。

## 出问题先看这里
- 完全看不到准星：确认没被 F8 隐藏、游戏不是独占全屏、目标屏幕选对了。
- 准星位置偏了：游戏分辨率或系统缩放变过就要重新取一次点。
- 准星挡住鼠标点击：可能停在「拖动定位」状态，回「准星」页点「完成定位」。
- 双击没反应：程序已经在运行了，看系统托盘。";
    }
